"""Open a (draft by default) Pull Request containing the evidence and CI results."""

from app.agent.nodes.common import ACTOR, fail, set_status
from app.agent.state import AgentState, Deps
from app.integrations.github_client import GitHubError
from app.schemas.incident import Incident, IncidentStatus
from app.security.redaction import redact


def _clean(text: str) -> str:
    """Redact secrets and defuse @mentions so untrusted text cannot ping people."""
    return redact(text).replace("@", "@\u200b")


def build_pr_body(incident: Incident) -> str:
    patch, policy = incident.patch, incident.policy
    ver = incident.verifications[-1] if incident.verifications else None
    lines = [
        f"## Automated repair proposal for incident `{incident.id}`",
        "",
        "> Generated by AI SRE Agent. **Review carefully before merging**; passing tests do not "
        "prove the fix is correct.",
        "",
        f"### Incident\n{_clean(incident.request.title)}",
        "",
        f"### Root cause (hypothesis)\n{_clean(incident.root_cause_summary)}",
        "",
        "### Evidence",
    ]
    for e in incident.evidence[:8]:
        lines.append(f"- **{e.id}** ({e.kind}) `{_clean(e.ref)}`")
    if patch:
        lines += [
            "",
            "### Patch",
            _clean(patch.summary),
            "",
            _clean(patch.rationale),
            "",
            f"Risk: **{patch.risk}** | Changed lines: {patch.changed_lines}",
        ]
        if patch.tests_to_run:
            lines.append(
                "Suggested tests: " + ", ".join(f"`{_clean(t)}`" for t in patch.tests_to_run)
            )
    if ver:
        lines += [
            "",
            "### Verification",
            f"Result: **{ver.conclusion}** (attempt {ver.attempt})"
            + (f" - [workflow run]({ver.run_url})" if ver.run_url else ""),
        ]
    if incident.approval and policy:
        lines += [
            "",
            f"Approved by `{_clean(incident.approval.approver)}` "
            f"(patch `{incident.approval.patch_sha256[:12]}`).",
        ]
    return "\n".join(lines)


def run(state: AgentState, deps: Deps) -> dict:
    incident_id = state["incident_id"]
    incident = deps.store.get(incident_id)
    req = incident.request
    source = deps.repos.get(req.repository)
    try:
        url = source.create_pull_request(
            req.repository,
            f"[AI SRE] {_clean(req.title)}"[:200],
            build_pr_body(incident),
            head=incident.branch or "",
            base=incident.base_branch or "main",
            draft=deps.settings.pr_draft,
        )
    except GitHubError as exc:
        return fail(deps, incident_id, f"Could not create Pull Request: {exc}")

    def mutate(inc: Incident) -> None:
        inc.pull_request_url = url

    deps.store.update(incident_id, mutate)
    set_status(deps, incident_id, IncidentStatus.PR_CREATED, url=url)
    deps.store.add_event(incident_id, ACTOR, "pull_request_created", {"url": url})
    return {"outcome": "done"}
